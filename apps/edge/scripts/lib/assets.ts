/**
 * Stage the static assets the Worker serves (wrangler.jsonc `assets.directory`):
 *
 * - the SPA build (`apps/web/dist`), without source maps and Vite's build manifest;
 * - the API reference bundle at `/api/docs/scalar.js` (blueprint: no third-party origins),
 *   served by the asset layer before the Worker runs;
 * - a `_headers` file: the chart's security headers for every asset, immutable caching for
 *   Vite's content-hashed `/assets/*`.
 *
 * The staging directory is rebuilt from scratch each time, so it never serves files the
 * current web build no longer has.
 */
import { cp, mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { EDGE_DIR, REPO_ROOT, type Target } from "./platform.ts";
import { chartSpaHeaders } from "./security-headers.ts";

export const WEB_DIST = join(REPO_ROOT, "apps", "web", "dist");
/** wrangler.jsonc `assets.directory`, per environment. */
export function assetsDir(target: Target): string {
  return join(EDGE_DIR, "dist", target === "production" ? "production-assets" : "public");
}

/** The self-contained Scalar bundle (same file the Node API serves, docs/DECISIONS.md D12). */
function scalarBundle(): string {
  // The package entry is dist/index.js; the standalone bundle sits next to it.
  return join(
    dirname(fileURLToPath(import.meta.resolve("@scalar/api-reference"))),
    "browser",
    "standalone.js",
  );
}

/**
 * The `_headers` file. Security headers come from the Helm chart (one policy for both modes,
 * see security-headers.ts); HSTS only in production (a browser that saw HSTS on localhost
 * would refuse plain http there). Only files that exist get here: misses go to the Worker
 * (`not_found_handling: "none"`), so `/assets/*` immutability never applies to a fallback.
 */
export async function headersFile(target: Target): Promise<string> {
  const security = await chartSpaHeaders({ https: target === "production" });
  return [
    "# Generated by apps/edge/scripts/ops.ts (assets) from deploy/helm/webflix (values.yaml",
    "# web.contentSecurityPolicy + templates/web/configmap.yaml). Do not edit.",
    "/*",
    ...security.map(([name, value]) => `  ${name}: ${value}`),
    "",
    "/assets/*",
    "  Cache-Control: public, max-age=31536000, immutable",
    "",
    "/api/docs/scalar.js",
    "  Cache-Control: public, max-age=86400",
    "",
  ].join("\n");
}

async function exists(path: string): Promise<boolean> {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

export interface StagedAssets {
  files: number;
  bytes: number;
}

export async function stageAssets(target: Target, out?: string): Promise<StagedAssets> {
  const directory = out ?? assetsDir(target);
  if (!(await exists(join(WEB_DIST, "index.html")))) {
    throw new Error(
      `No web build in ${relative(REPO_ROOT, WEB_DIST)} (pnpm --filter @webflix/web build)`,
    );
  }
  await rm(directory, { recursive: true, force: true });
  await cp(WEB_DIST, directory, {
    recursive: true,
    filter: (source) => {
      const path = relative(WEB_DIST, source);
      return !path.endsWith(".map") && path !== ".vite" && !path.startsWith(`.vite/`);
    },
  });
  const docs = join(directory, "api", "docs");
  await mkdir(docs, { recursive: true });
  await cp(scalarBundle(), join(docs, "scalar.js"));
  await writeFile(join(directory, "_headers"), await headersFile(target));

  let files = 0;
  let bytes = 0;
  const walk = async (dir: string): Promise<void> => {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) await walk(path);
      else {
        files += 1;
        bytes += (await stat(path)).size;
      }
    }
  };
  await walk(directory);
  return { files, bytes };
}
