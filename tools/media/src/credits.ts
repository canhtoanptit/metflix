/**
 * `webflix-media credits`: regenerate docs/CREDITS.md from the sources of truth (the open
 * films in @webflix/catalog, the pinned photo library, the font registry), so the credits can
 * never drift from what the pipeline actually uses.
 */
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { CURATED_PREVIEWS, catalog, openFilms } from "@webflix/catalog";
import { resolveDirection } from "./art/direction.ts";
import { familyDir, readFontRegistry } from "./art/fonts-fetch.ts";
import { readPhotoLibrary } from "./art/photos.ts";
import { FONTS_DIR, REPO_ROOT } from "./paths.ts";
import { writeFileAtomic } from "./util/fs.ts";

const md = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

async function fontLicense(family: string): Promise<string> {
  const text = await readFile(join(FONTS_DIR, "licenses", `${familyDir(family)}.txt`), "utf8");
  if (/SIL OPEN FONT LICENSE/i.test(text)) return "OFL-1.1";
  if (/Apache License/i.test(text)) return "Apache-2.0";
  if (/UBUNTU FONT LICENCE/i.test(text)) return "UFL-1.0";
  return "see licence file";
}

export async function writeCredits(): Promise<number> {
  const people = new Map(catalog.people.map((person) => [person.id, person.name]));
  const lines: string[] = [];
  lines.push(
    "# Credits",
    "",
    "Every piece of media in Webflix is freely licensed or original. This file is generated by",
    "`webflix-media credits` from `packages/catalog/src/data/open-films.ts`,",
    "`tools/media/sources/photos.json` and `tools/media/fonts/fonts.json`; edit those, not this file.",
    "",
    "## Films",
    "",
    "The footage of every title is from these open films. The real films appear in the catalog",
    "under their own names with their real credits; fictional titles borrow their footage",
    "(text-free cuts and chapters), which the licences allow with attribution. The section",
    "*Footage of the fictional titles* below lists exactly which film each one plays.",
    "",
    "| Film | Year | Licence | Attribution | Source |",
    "| --- | --- | --- | --- | --- |",
  );
  for (const film of openFilms) {
    lines.push(
      `| ${md(film.name)} | ${film.year} | [${film.license.license}](${film.license.licenseUrl}) | ${md(film.license.attribution)} | [project](${film.license.sourceUrl ?? film.source.url}) · [file](${film.source.url}) |`,
    );
  }
  lines.push("", "### Credits of the open films", "");
  for (const title of catalog.titles.filter((entry) => entry.license)) {
    const role = (label: string, ids: readonly string[]) =>
      ids.length ? `${label}: ${ids.map((id) => people.get(id) ?? id).join(", ")}` : null;
    const cast = title.cast.length
      ? `Cast: ${title.cast.map((credit) => `${people.get(credit.personId) ?? credit.personId}${credit.character ? ` (${credit.character})` : ""}`).join(", ")}`
      : null;
    const parts = [
      role("Directed by", title.directorIds),
      role("Written by", title.writerIds),
      cast,
    ].filter(Boolean);
    lines.push(`- **${title.name}** (${title.releaseYear}). ${parts.join(". ")}.`);
  }
  lines.push(
    "",
    "Subtitles are the films' official or community translations, from the project sites,",
    "video.blender.org and Wikimedia Commons TimedText, under the films' licences.",
    "",
    "Licence notes. Where mirrors disagree, the official project statement wins: Cosmos",
    "Laundromat is CC BY 3.0 (gooseberry.blender.org/about; Commons tags it BY-SA) and",
    "Caminandes 2 is CC BY 3.0 (the archived caminandes.com sharing page). Blender Studio",
    "publishes Caminandes 3 under Creative Commons Attribution without a version; Commons",
    "records 3.0. Agent 327 is excluded: it is CC BY-ND.",
  );
  // Which footage every fictional title plays, for attribution and so nobody mistakes it.
  const films = new Map(openFilms.map((film) => [film.source.url, film]));
  const assets = new Map(catalog.videoAssets.map((asset) => [asset.id, asset]));
  const clock = (sec: number) =>
    `${Math.floor(sec / 60)}:${String(Math.round(sec % 60)).padStart(2, "0")}`;
  const filmOf = (assetId: string) => {
    const asset = assets.get(assetId);
    return asset?.source.kind === "download" ? films.get(asset.source.url) : undefined;
  };
  const cut = (assetId: string) => {
    const asset = assets.get(assetId);
    if (asset?.source.kind !== "download") return assetId;
    const film = filmOf(assetId);
    const start = asset.source.startSec ?? 0;
    const end = start + (asset.source.durationSec ?? (film?.durationSec ?? start) - start);
    return `${film?.name ?? asset.source.url} ${clock(start)}–${clock(end)}`;
  };
  lines.push(
    "",
    "## Footage of the fictional titles",
    "",
    "The fictional titles have no footage of their own, so their movies and episodes play the",
    "open films above, said plainly here. Only each film's text-free story is used: no studio",
    "cards, title cards or credit rolls (measured to 1/8 s and kept at least a second clear;",
    "the timecodes are in `open-films.ts`), and footage is matched to the title's medium and",
    "genre as far as the pool allows (one live-action film, Tears of Steel; the others are",
    "animated). Previews never borrow unrelated footage: a fictional title previews either a",
    "reviewed excerpt that fits it (*curated*) or a motion-art clip rendered from its own key",
    "art (*key art*), which is original work.",
    "",
    "| Title | Plays | Preview |",
    "| --- | --- | --- |",
  );
  for (const title of catalog.titles.filter((entry) => !entry.license)) {
    const played =
      title.type === "movie"
        ? cut(title.videoAssetId)
        : `${[
            ...new Set(
              title.seasons.flatMap((season) =>
                season.episodes.map((episode) => filmOf(episode.videoAssetId)?.name ?? "?"),
              ),
            ),
          ].join(", ")}, text-free chapters`;
    const preview = CURATED_PREVIEWS[title.id]
      ? `curated: ${cut(title.previewAssetId ?? "")}`
      : "key art";
    lines.push(`| ${md(title.name)} | ${md(played)} | ${md(preview)} |`);
  }
  lines.push(
    "",
    "## Photographs",
    "",
    "Key art, posters, cards and episode stills of the fictional titles are built from these",
    "photographs (graded, cropped and composited with original typography). Artwork derived from",
    "a CC BY-SA photograph is itself available under the same CC BY-SA licence.",
    "",
    "| Photo | Used for | Author | Licence |",
    "| --- | --- | --- | --- |",
  );
  // Only photographs some title's art direction actually uses.
  const library = await readPhotoLibrary();
  const photos = new Map(library.map((photo) => [photo.id, photo]));
  const genres = new Map(catalog.genres.map((genre) => [genre.id, genre.slug]));
  const usedBy = new Map<string, string>();
  for (const title of catalog.titles) {
    const direction = resolveDirection(
      title,
      title.genreIds.map((id) => genres.get(id) ?? "drama"),
      photos,
      () => null,
    );
    const used = [
      ...(direction.source.kind === "photo" ? [direction.source.photo] : []),
      ...direction.stills,
    ];
    for (const photo of used) usedBy.set(photo.id, title.name);
  }
  for (const photo of library) {
    const used = usedBy.get(photo.id);
    if (!used) continue;
    lines.push(
      `| [${md(photo.caption)}](${photo.page}) | ${md(used)} | ${md(photo.author)} | [${photo.license}](${photo.licenseUrl}) |`,
    );
  }
  lines.push(
    "",
    "## Fonts",
    "",
    "Title treatments are set in these openly licensed fonts, self-hosted in `tools/media/fonts`",
    "(licence texts in `tools/media/fonts/licenses`). They are rendered to outlines at build time;",
    "no font is loaded at runtime.",
    "",
    "| Family | Style | Licence |",
    "| --- | --- | --- |",
  );
  const seen = new Set<string>();
  for (const font of (await readFontRegistry()).fonts) {
    const key = `${font.family}:${font.weight}:${font.italic ? "i" : ""}`;
    if (seen.has(key)) continue;
    seen.add(key);
    lines.push(
      `| [${font.family}](https://fonts.google.com/specimen/${font.family.replaceAll(" ", "+")}) | ${font.weight}${font.italic ? " italic" : ""} | ${await fontLicense(font.family)} |`,
    );
  }
  lines.push(
    "",
    "## Original work",
    "",
    "- Profile avatars, procedural backgrounds, title treatments and the synthetic fallback",
    "  stream are generated by `tools/media` and are original to Webflix.",
    "- Catalog copy (titles, synopses, episode guides) and every person credited on a fictional",
    "  title are invented; any resemblance to real people or productions is coincidental.",
    "",
    "## Software",
    "",
    "- [FFmpeg](https://ffmpeg.org) 8 (LGPL/GPL, with libx264), run from Alpine Linux packages",
    "  in Docker; [sharp](https://sharp.pixelplumbing.com)/libvips (Apache-2.0/LGPL);",
    "  [fontkit](https://github.com/foliojs/fontkit) (MIT); [ThumbHash](https://evanw.github.io/thumbhash/) (MIT).",
    "",
  );
  await writeFileAtomic(join(REPO_ROOT, "docs", "CREDITS.md"), lines.join("\n"));
  console.log(`wrote docs/CREDITS.md (${openFilms.length} films, ${usedBy.size} photos)`);
  return 0;
}
