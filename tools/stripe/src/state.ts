import { appendFileSync, existsSync, readFileSync, rmSync } from "node:fs";
import { paths } from "./paths.ts";
import { ensurePrivateDir, tightenPermissions, writePrivateFile } from "./secure-fs.ts";

/**
 * `.cache/stripe/sandbox.json` (0600, git-ignored): everything other tooling needs to talk to
 * the sandbox. Read it with `readState()`; never print it.
 */
export interface SandboxState {
  schema: 1;
  /** Absent or "cli-sandbox": provisioned by `stripe sandboxes create`; "imported": make stripe-use-key. */
  source?: "cli-sandbox" | "imported";
  accountId: string;
  /** The key the CLI saved (a restricted sandbox key, `rkcs_test_…`, from CLI 1.55.14). */
  secretKey: string;
  publishableKey: string;
  /** Capability URL: whoever opens it can claim the sandbox. Shown only by `make stripe-claim`. */
  claimUrl: string | null;
  /** Calendar date (UTC) the CLI reports; the CLI treats the sandbox as expired from 00:00 UTC. */
  expiresOn: string | null;
  createdAt: string;
  cliVersion: string;
  /** Webhook signing secret of the `stripe listen` session (stable across restarts). */
  webhookSecret: string | null;
  webhookSecretCapturedAt: string | null;
}

export function isSandboxState(value: unknown): value is SandboxState {
  if (typeof value !== "object" || value === null) return false;
  const v = value as Record<string, unknown>;
  return (
    v.schema === 1 &&
    (v.source === undefined || v.source === "cli-sandbox" || v.source === "imported") &&
    typeof v.accountId === "string" &&
    typeof v.secretKey === "string" &&
    typeof v.publishableKey === "string" &&
    (v.claimUrl === null || typeof v.claimUrl === "string") &&
    (v.expiresOn === null || typeof v.expiresOn === "string") &&
    typeof v.createdAt === "string" &&
    typeof v.cliVersion === "string" &&
    (v.webhookSecret === null || typeof v.webhookSecret === "string")
  );
}

export function readState(): SandboxState | null {
  if (!existsSync(paths.stateFile)) return null;
  tightenPermissions(paths.stateFile);
  const parsed: unknown = JSON.parse(readFileSync(paths.stateFile, "utf8"));
  if (!isSandboxState(parsed)) {
    throw new Error(`${paths.stateFile} is not a sandbox state file; run make stripe-reset.`);
  }
  return parsed;
}

export function requireState(): SandboxState {
  const state = readState();
  if (!state) throw new Error("No Stripe sandbox is configured. Run `make stripe-sandbox` first.");
  return state;
}

/** Write the JSON state and its dotenv twin, both 0600. */
export function writeState(state: SandboxState): void {
  writePrivateFile(paths.stateFile, `${JSON.stringify(state, null, 2)}\n`);
  writePrivateFile(paths.envFile, renderEnvFile(state));
}

export function renderEnvFile(state: SandboxState): string {
  const lines = [
    "# Generated by `make stripe-sandbox` / `make stripe-listen`. Test-mode credentials:",
    "# git-ignored, owner-only. Do not copy into tracked files.",
    `STRIPE_ACCOUNT_ID=${state.accountId}`,
    `STRIPE_SECRET_KEY=${state.secretKey}`,
    `STRIPE_PUBLISHABLE_KEY=${state.publishableKey}`,
    `STRIPE_WEBHOOK_SECRET=${state.webhookSecret ?? ""}`,
    `STRIPE_SANDBOX_EXPIRES_ON=${state.expiresOn ?? ""}`,
  ];
  return `${lines.join("\n")}\n`;
}

export function deleteState(): string[] {
  const removed: string[] = [];
  for (const file of [paths.stateFile, paths.envFile]) {
    if (existsSync(file)) {
      rmSync(file);
      removed.push(file);
    }
  }
  return removed;
}

/** Append a non-secret line to the history of sandboxes this checkout created or forgot. */
export function appendHistory(entry: {
  event: string;
  accountId: string;
  expiresOn: string | null;
}): void {
  ensurePrivateDir(paths.cache);
  appendFileSync(
    paths.historyFile,
    `${JSON.stringify({ at: new Date().toISOString(), ...entry })}\n`,
    {
      mode: 0o600,
    },
  );
}

export function readHistory(): Array<{
  at: string;
  event: string;
  accountId: string;
  expiresOn: string | null;
}> {
  if (!existsSync(paths.historyFile)) return [];
  return readFileSync(paths.historyFile, "utf8")
    .split("\n")
    .filter((line) => line.trim() !== "")
    .map(
      (line) =>
        JSON.parse(line) as {
          at: string;
          event: string;
          accountId: string;
          expiresOn: string | null;
        },
    );
}
